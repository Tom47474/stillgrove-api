CREATE TABLE ai_generations (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id BIGINT UNSIGNED NOT NULL,
    conversation_id BIGINT UNSIGNED NOT NULL,
    client_request_id VARCHAR(64) NOT NULL,
    user_message_id BIGINT UNSIGNED NOT NULL,
    assistant_message_id BIGINT UNSIGNED NOT NULL,
    model_name VARCHAR(100) NOT NULL,
    provider_name VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
    finish_reason VARCHAR(50) NULL,
    input_tokens INT UNSIGNED NULL,
    output_tokens INT UNSIGNED NULL,
    latency_ms INT UNSIGNED NULL,
    cost_micros BIGINT UNSIGNED NULL,
    retry_count INT UNSIGNED NOT NULL DEFAULT 0,
    error_code VARCHAR(100) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    finished_at DATETIME(3) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_ai_generations_user_request (user_id, client_request_id),
    UNIQUE KEY uk_ai_generations_user_message (user_message_id),
    UNIQUE KEY uk_ai_generations_assistant_message (assistant_message_id),
    KEY idx_ai_generations_conversation (conversation_id, created_at),
    CONSTRAINT fk_ai_generations_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_ai_generations_conversation FOREIGN KEY (conversation_id) REFERENCES conversations (id),
    CONSTRAINT fk_ai_generations_user_message FOREIGN KEY (user_message_id) REFERENCES messages (id),
    CONSTRAINT fk_ai_generations_assistant_message FOREIGN KEY (assistant_message_id) REFERENCES messages (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
